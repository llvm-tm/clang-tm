#!/usr/bin/env bash
# =============================================================================
# install-benchmarks.sh — Set up and build TM benchmarks with installed clang-tm
#
# Creates a standalone benchmark workspace outside the repo that uses the
# system-wide clang-tm installation.
#
# Usage:
#   ./install-benchmarks.sh [OPTIONS]
#
# Options:
#   --prefix DIR     Prefix where clang-tm is installed   (env: PREFIX)
#   --destdir DIR    Staging directory                     (env: DESTDIR)
#   --benchdir DIR   Where to create the workspace         (env: BENCHDIR)
#                     default: ~/tm-benchmarks
#   -y, --yes        Non-interactive
#   --skip-build     Only copy sources, don't compile
#   --dry-run        Print what would be done, do nothing
#   -h, --help       Show this message
# =============================================================================

set -euo pipefail

if [ -t 1 ]; then
    RED='\033[0;31m'; GREEN='\033[0;32m'; YELLOW='\033[1;33m'
    BOLD='\033[1m'; NC='\033[0m'
else
    RED=''; GREEN=''; YELLOW=''; BOLD=''; NC=''
fi

info()  { printf "${GREEN}==>${NC} ${BOLD}%s${NC}\n" "$*"; }
warn()  { printf "${YELLOW}==>${NC} ${BOLD}%s${NC}\n" "$*"; }
err()   { printf "${RED}==>${NC} ${BOLD}%s${NC}\n" "$*" >&2; }
die()   { err "$@"; exit 1; }

need_cmd() {
    if ! command -v "$1" >/dev/null 2>&1; then
        die "Required command '$1' not found."
    fi
}

SCRIPT_DIR="$(cd "$(dirname "$0")" && pwd)"
PROJECT_ROOT="$(cd "$SCRIPT_DIR/.." && pwd)"

PREFIX="${PREFIX:-/usr/local}"
DESTDIR="${DESTDIR:-}"
BENCHDIR="${BENCHDIR:-$HOME/tm-benchmarks}"
YES=0
SKIP_BUILD=0
DRY_RUN=0

while [ $# -gt 0 ]; do
    case "$1" in
        --prefix)
            PREFIX="$2"; shift 2 ;;
        --prefix=*)
            PREFIX="${1#*=}"; shift ;;
        --destdir)
            DESTDIR="$2"; shift 2 ;;
        --destdir=*)
            DESTDIR="${1#*=}"; shift ;;
        --benchdir)
            BENCHDIR="$2"; shift 2 ;;
        --benchdir=*)
            BENCHDIR="${1#*=}"; shift ;;
        -y|--yes)
            YES=1; shift ;;
        --skip-build)
            SKIP_BUILD=1; shift ;;
        --dry-run)
            DRY_RUN=1; shift ;;
        -h|--help)
            sed -n 's/^# \?//p' "$0" | sed '1,/^$/d' | head -n -1
            exit 0 ;;
        *)
            die "Unknown option: $1. Try --help." ;;
    esac
done

# ---- Verify clang-tm is installed ----
CLANG_TM="${DESTDIR}${PREFIX}/bin/clang-tm"
if [ ! -f "$CLANG_TM" ]; then
    # Maybe it's on PATH
    CLANG_TM="$(command -v clang-tm || true)"
fi
if [ -z "$CLANG_TM" ] || [ ! -f "$CLANG_TM" ]; then
    die "clang-tm not found. Run install.sh first, or ensure clang-tm is on PATH."
fi
info "Using clang-tm: $CLANG_TM"

CLANG_TM_BIN="$(dirname "$CLANG_TM")"
TM_LIB_DIR="$(cd "$CLANG_TM_BIN/../lib/clang-tm" && pwd)"
TM_INCLUDE="$TM_LIB_DIR/include"
TM_RUNTIMES="$TM_LIB_DIR/runtimes"

if [ ! -d "$TM_INCLUDE" ] || [ ! -d "$TM_RUNTIMES" ]; then
    die "clang-tm installation incomplete: missing $TM_INCLUDE or $TM_RUNTIMES"
fi

# ---- Confirm ----
info "Creating benchmark workspace at: ${BOLD}$BENCHDIR${NC}"
info "  Backends available:"
for f in "$TM_RUNTIMES"/*.cpp; do
    printf "    - %s\n" "$(basename "$f" .cpp)"
done

if [ "$YES" -eq 0 ] && [ "$DRY_RUN" -eq 0 ]; then
    printf "Continue? [Y/n] "
    if [ -t 0 ]; then
        read -r reply
    elif [ -e /dev/tty ]; then
        read -r reply </dev/tty
    else
        reply="y"
    fi
    case "$reply" in
        n|N|no|NO) die "Aborted." ;;
    esac
fi

if [ "$DRY_RUN" -eq 1 ]; then
    info "Dry-run — nothing installed."
    exit 0
fi

# ---- Create workspace ----
mkdir -p "$BENCHDIR"

# ---- Copy bank benchmark (simple correctness test) ----
BENCH_SRC="$PROJECT_ROOT/benchmarks/test/bank/bank.cpp"
if [ ! -f "$BENCH_SRC" ]; then
    # Not in a repo checkout — fetch from GitHub
    info "Downloading benchmark sources from GitHub..."
    TMP_SRC="$BENCHDIR/.tmp_bank"
    curl -fsSL -o "$TMP_SRC" \
        "https://raw.githubusercontent.com/llvm-tm/clang-tm/main/benchmarks/test/bank/bank.cpp"
    mv "$TMP_SRC" "$BENCHDIR/bank.cpp"
else
    cp "$BENCH_SRC" "$BENCHDIR/bank.cpp"
fi

# ---- Create Makefile ----
cat > "$BENCHDIR/Makefile" << MAKEEOF
# Makefile for clang-tm benchmarks — auto-generated by install-benchmarks.sh
CLANG_TM   := $CLANG_TM
CXXFLAGS   := -std=c++20 -O3 -pthread -I$TM_LIB_DIR
RUNTIMES   := $TM_RUNTIMES
BIN_DIR    := bin

.PHONY: all clean test

all: \$(BIN_DIR) \\
	bank_uninstrumented \\
	bank_singlelock bank_norec bank_tl2 bank_tinystm bank_swiss

\$(BIN_DIR):
	mkdir -p \$(BIN_DIR)

bank_uninstrumented: bank.cpp | \$(BIN_DIR)
	clang++ \$(CXXFLAGS) bank.cpp -o \$(BIN_DIR)/\$@

bank_singlelock: bank.cpp | \$(BIN_DIR)
	\$(CLANG_TM) \$(CXXFLAGS) --runtime \$(RUNTIMES)/SingleGlobalLock_runtime.cpp -o \$(BIN_DIR)/\$@ bank.cpp

bank_norec: bank.cpp | \$(BIN_DIR)
	\$(CLANG_TM) \$(CXXFLAGS) -I\$(RUNTIMES)/../NOrec --runtime \$(RUNTIMES)/NOrec_runtime.cpp -o \$(BIN_DIR)/\$@ bank.cpp

bank_tl2: bank.cpp | \$(BIN_DIR)
	\$(CLANG_TM) \$(CXXFLAGS) --runtime \$(RUNTIMES)/tl2_runtime.cpp -o \$(BIN_DIR)/\$@ bank.cpp

bank_tinystm: bank.cpp | \$(BIN_DIR)
	\$(CLANG_TM) \$(CXXFLAGS) -I\$(RUNTIMES)/../TinySTM -DDESIGN_WBCTL --runtime \$(RUNTIMES)/TinySTM_runtime.cpp -o \$(BIN_DIR)/\$@ bank.cpp

bank_swiss: bank.cpp | \$(BIN_DIR)
	\$(CLANG_TM) \$(CXXFLAGS) --runtime \$(RUNTIMES)/SwissTM_runtime.cpp -o \$(BIN_DIR)/\$@ bank.cpp

test: all
	@echo "=== Bank correctness test ==="
	@for b in singlelock norec tl2 tinystm; do \\
		echo "--- bank_\$\$b ---"; \\
		./bin/bank_\$\$b -t 2 -a 64 -d 2000 -r 10 -w 0 || echo "FAILED"; \\
	done

clean:
	rm -rf \$(BIN_DIR)
MAKEEOF

info "Created Makefile and copied bank.cpp to $BENCHDIR"

# ---- Build ----
if [ "$SKIP_BUILD" -eq 0 ]; then
    info "Building benchmarks (this may take a few minutes)..."
    make -C "$BENCHDIR" all -j"$(nproc 2>/dev/null || sysctl -n hw.ncpu 2>/dev/null || echo 4)"
    info "Build complete:"
    ls -1 "$BENCHDIR/bin/"
fi

echo ""
info "Benchmark workspace ready at: ${BOLD}$BENCHDIR${NC}"
echo ""
printf "  ${BOLD}Run tests:${NC}\n"
printf "    make -C $BENCHDIR test\n"
echo ""
printf "  ${BOLD}Run manually:${NC}\n"
printf "    $BENCHDIR/bin/bank_singlelock -t 4 -a 256 -d 5000 -r 20\n"
