#!/usr/bin/env python3
"""
compare_real_sim.py — Compare real C++ TM backends vs Rust simulation.

Runs C++ benchmarks (bank + 8 STAMP) across all backends with trace
generation, replays through tm-check (WBCTL model) and tm-sim (Rust
backend), and compares correctness and speed.

The simulator mmap's a fixed address range (0x7f00_0000_0000).  Real
C++ benchmarks allocate from the OS heap (region-allocator address).
This means tm-sim can only replay traces whose addresses fall in the
simulator's range — i.e., traces generated by tm-gen.  Real C++ traces
are replayed through tm-check (WBCTL model, no memory access) for
transaction-level correctness, and through compare_sim.py for aggregate
fidelity metrics.

Usage:
  python3 compare_real_sim.py                                  # run all
  python3 compare_real_sim.py --backends NOREC,TL2,TINYSTM      # selected
  python3 compare_real_sim.py --benchmarks bank,vacation        # selected
  python3 compare_real_sim.py --csv results.csv                 # output CSV
  python3 compare_real_sim.py --threads 4                       # single thread
  python3 compare_real_sim.py --duration 1000                   # 1 sec per run
  python3 compare_real_sim.py --sim-only                       # sim only, no real
  python3 compare_real_sim.py --real-only                      # real only, no sim
"""

